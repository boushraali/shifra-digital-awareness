// Vercel build step (Root Directory = server):
//  1) builds the React app in ../client
//  2) copies it to ./public (served by Vercel's CDN)
//  3) embeds index.html into the function (SPA routes like /student/journey)
//  4) applies the database schema + the seven worlds (needs DATABASE_URL at build time)
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const run = (cmd, cwd) => execSync(cmd, { cwd, stdio: 'inherit', env: process.env });
const server = process.cwd();
const client = path.resolve(server, '..', 'client');

run('npm ci --no-audit --no-fund', client);
run('npm run build', client);

const pub = path.join(server, 'public');
fs.rmSync(pub, { recursive: true, force: true });
fs.cpSync(path.join(client, 'dist'), pub, { recursive: true });

const html = fs.readFileSync(path.join(client, 'dist', 'index.html'), 'utf8');
fs.writeFileSync(path.join(server, 'src', 'generated', 'indexHtml.ts'),
  `// generated by scripts/vercel-build.mjs\nexport const INDEX_HTML = ${JSON.stringify(html)};\n`);

if (process.env.DATABASE_URL && process.env.JWT_SECRET) {
  run('npx tsx src/migrate.ts', server);
  if (process.env.BOOTSTRAP_TEACHER_EMAIL) run('npx tsx src/bootstrapTeacher.ts', server);
}
else console.warn('⚠ DATABASE_URL / JWT_SECRET not set — skipped database migration. Add them in Vercel → Settings → Environment Variables and redeploy.');
console.log('✓ vercel build done');
